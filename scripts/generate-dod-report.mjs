#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const OUT = path.join(repoRoot, 'docs/lexi/DOD-REPORT.md');

export const ITEMS = [
  { id: 1, label: 'Nav items render without console errors', kind: 'auto' },
  { id: 2, label: 'Buttons report success/failure visibly', kind: 'auto' },
  { id: 3, label: 'Forms persist + read back values', kind: 'auto' },
  { id: 4, label: 'Every link returns 200 / opens correctly', kind: 'auto' },
  { id: 5, label: 'Every API endpoint returns 200 or visible 4xx', kind: 'auto' },
  { id: 6, label: 'Five broken endpoints fixed', kind: 'auto' },
  { id: 7, label: 'Upstream features have Lexi counterpart', kind: 'auto' },
  { id: 8, label: 'Light/dark in three browsers', kind: 'manual' },
  { id: 9, label: '⌘K reachable from any screen', kind: 'auto' },
  { id: 10, label: 'Live event ≤500ms p95', kind: 'auto' },
  { id: 11, label: 'No external network beyond user-configured', kind: 'auto' },
  { id: 12, label: 'launchd loaded + survives logout', kind: 'partial' },
  { id: 13, label: 'kill -9 → restart ≤3s', kind: 'auto' },
  { id: 14, label: 'Doctor green on clean install', kind: 'auto' },
  { id: 15, label: 'Build commands documented', kind: 'auto' },
  { id: 16, label: 'Diff scope only allowed paths', kind: 'auto' },
  { id: 17, label: 'Fresh merge conflict-free', kind: 'auto' },
];

export function writeReport(results /* Map<id, {status, notes}> */) {
  const branch = execFileSync('git', ['branch', '--show-current'], { cwd: repoRoot, encoding: 'utf8' }).trim();
  const commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: repoRoot, encoding: 'utf8' }).trim();

  const lines = [];
  lines.push('# Lexi Dashboard — Definition of Done Report');
  lines.push('');
  lines.push('> Auto-generated by `npm run dod`. Do not edit by hand.');
  lines.push('');
  lines.push(`**Last run:** ${new Date().toISOString()}`);
  lines.push(`**Branch:** ${branch}`);
  lines.push(`**Commit:** ${commit}`);
  lines.push('');
  lines.push('## Results');
  lines.push('');
  lines.push('| # | Criterion | Status | Notes |');
  lines.push('|---|---|---|---|');
  let pass = 0; let fail = 0;
  for (const item of ITEMS) {
    const r = results.get(item.id) ?? { status: 'SKIP', notes: '' };
    if (r.status === 'PASS') pass++; else if (r.status === 'FAIL') fail++;
    lines.push(`| ${item.id} | ${item.label} | ${r.status} | ${r.notes || (item.kind === 'manual' ? 'manual' : '—')} |`);
  }
  lines.push('');
  lines.push('## Summary');
  lines.push('');
  lines.push(`- PASS: ${pass} / 17`);
  lines.push(`- FAIL: ${fail}`);
  lines.push(`- Manual / Skip: ${17 - pass - fail}`);
  lines.push('');
  lines.push(fail === 0 && pass === 17 ? '**OVERALL: GREEN — Lexi dashboard meets all DoD criteria.**' : '**OVERALL: NOT YET COMPLETE.**');
  writeFileSync(OUT, lines.join('\n'));
}

if (import.meta.url === `file://${process.argv[1]}`) {
  // Stand-alone invocation = write the empty template
  const empty = new Map();
  writeReport(empty);
  console.log(`Wrote ${OUT}`);
}
